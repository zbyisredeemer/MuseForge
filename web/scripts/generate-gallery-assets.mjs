import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(here, "..");
const galleryDir = path.join(webRoot, "public", "gallery");
const outputFile = path.join(webRoot, "src", "generated", "galleryAssets.ts");

const preferredExtensions = [".webp", ".jpg", ".jpeg", ".png"];
const minimumWidth = 768;
const minimumHeight = 960;

function imageId(fileName) {
  return path.basename(fileName, path.extname(fileName)).replaceAll("_", "-");
}

function readJpegSize(buffer) {
  if (buffer.length < 4 || buffer[0] !== 0xff || buffer[1] !== 0xd8) return null;
  let offset = 2;

  while (offset + 9 < buffer.length) {
    if (buffer[offset] !== 0xff) {
      offset += 1;
      continue;
    }

    const marker = buffer[offset + 1];
    const sofMarkers = new Set([
      0xc0, 0xc1, 0xc2, 0xc3, 0xc5, 0xc6, 0xc7,
      0xc9, 0xca, 0xcb, 0xcd, 0xce, 0xcf,
    ]);

    if (sofMarkers.has(marker)) {
      return {
        height: buffer.readUInt16BE(offset + 5),
        width: buffer.readUInt16BE(offset + 7),
      };
    }

    if (marker === 0xd8 || marker === 0xd9) {
      offset += 2;
      continue;
    }

    const segmentLength = buffer.readUInt16BE(offset + 2);
    if (!segmentLength) return null;
    offset += segmentLength + 2;
  }

  return null;
}

function readPngSize(buffer) {
  const signature = "89504e470d0a1a0a";
  if (buffer.length < 24 || buffer.subarray(0, 8).toString("hex") !== signature) return null;
  return {
    width: buffer.readUInt32BE(16),
    height: buffer.readUInt32BE(20),
  };
}

function readImageSize(filePath) {
  const extension = path.extname(filePath).toLowerCase();
  const buffer = fs.readFileSync(filePath);
  if (extension === ".jpg" || extension === ".jpeg") return readJpegSize(buffer);
  if (extension === ".png") return readPngSize(buffer);
  return null;
}

if (!fs.existsSync(galleryDir)) {
  throw new Error(`Gallery directory not found: ${galleryDir}`);
}

const files = fs
  .readdirSync(galleryDir)
  .filter((fileName) => preferredExtensions.includes(path.extname(fileName).toLowerCase()));

const selected = new Map();

for (const fileName of files) {
  const id = imageId(fileName);
  const extension = path.extname(fileName).toLowerCase();
  const current = selected.get(id);

  if (
    !current ||
    preferredExtensions.indexOf(extension) <
      preferredExtensions.indexOf(path.extname(current).toLowerCase())
  ) {
    selected.set(id, fileName);
  }
}

const assets = {};
const lowResolution = [];

for (const [id, fileName] of [...selected.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  const dimensions = readImageSize(path.join(galleryDir, fileName));
  assets[id] = {
    src: `/gallery/${fileName}`,
    width: dimensions?.width ?? 0,
    height: dimensions?.height ?? 0,
  };

  if (
    dimensions &&
    (dimensions.width < minimumWidth || dimensions.height < minimumHeight)
  ) {
    lowResolution.push({ id, fileName, ...dimensions });
  }
}

const generated = `// AUTO-GENERATED by web/scripts/generate-gallery-assets.mjs.
// Do not edit by hand. Run: npm run gallery:assets

export type GalleryAsset = {
  src: string;
  width: number;
  height: number;
};

export const galleryAssets: Record<string, GalleryAsset> = ${JSON.stringify(assets, null, 2)};

export const galleryAssetQuality = {
  recommendedWidth: 1024,
  recommendedHeight: 1280,
  minimumWidth: ${minimumWidth},
  minimumHeight: ${minimumHeight},
} as const;
`;

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
fs.writeFileSync(outputFile, generated, "utf8");

console.log(`[gallery-assets] generated ${Object.keys(assets).length} preview entries`);

for (const item of lowResolution) {
  console.warn(
    `[gallery-assets] LOW RES ${item.fileName}: ${item.width}x${item.height}; minimum is ${minimumWidth}x${minimumHeight}`,
  );
}

if (process.env.GALLERY_ASSET_STRICT === "1" && lowResolution.length > 0) {
  process.exitCode = 1;
}
